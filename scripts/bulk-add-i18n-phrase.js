function escapeRegex(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function addToFile(content) {
  let out = content;
  for (const phrase of phrases) {
    const phrasePattern = escapeRegex(phrase).replace(/\s+/g, '\\s+');
    const re = new RegExp(`(<([a-zA-Z0-9]+)([^>]*?)>)(\\s*)${phrasePattern}(\\s*</\\2>)`, 'gs');
    out = out.replace(re, (full, openTag, tag, attrs, pre, post) => {
      if (openTag.includes('data-i18n=')) return full;
      if (tag.toLowerCase() === 'script' || tag.toLowerCase() === 'style') return full;
      const injected = openTag.slice(0, -1) + ` data-i18n="phrase.${phrase}">`;
      return `${injected}${pre}${phrase}${post}`;
    });
  }
  return out;
}

for (const fullPath of files) {
  const original = fs.readFileSync(fullPath, 'utf8');
  const updated = addToFile(original);
  if (updated !== original) {
    fs.writeFileSync(fullPath, updated);
    console.log('updated ' + path.relative(root, fullPath));
  }
}
